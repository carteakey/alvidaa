def _dns_block():
    """dnsmasq block file derived from ADSFW_HOSTS (single source of truth,
    no second host list in this repo). Bare address=/host/ -> NXDOMAIN for
    that name and all its subdomains, A and AAAA alike."""
    out = ["# generated by tools/u7q/scripts/make_min_installer.py from ADSFW_HOSTS",
           "# do not hand-edit: change ADSFW_HOSTS and rebuild instead"]
    for line in ADSFW_HOSTS.splitlines():
        s = line.strip()
        if s and not s.startswith("#"):
            out.append("address=/%s/" % s)
    return "\n".join(out) + "\n"

DNS_BLOCK = _dns_block()

DNSMASQ_STOP = r"""#!/bin/sh
# staged resolver teardown: stop dnsmasq, unbind /etc/resolv.conf, flush
# nat redirects. Run over the root-SSH lane; idempotent.
D=/APPS/.re_sshd
BUSY=/usr/local/bin/busybox
{
  if [ -f "$D/dnsmasq.pid" ]; then
      kill "$(cat "$D/dnsmasq.pid")" 2>/dev/null
      rm -f "$D/dnsmasq.pid"
      echo "killed dnsmasq"
  fi
  if "$BUSY" mount 2>/dev/null | grep -q "resolv.conf.la.*on /etc/resolv.conf"; then
      "$BUSY" umount /etc/resolv.conf 2>&1 && echo "unbound /etc/resolv.conf"
  fi
  if [ -s "$D/resolv.conf.orig" ] && grep -q "nameserver 127.0.0.1" /etc/resolv.conf 2>/dev/null; then
      cp -f "$D/resolv.conf.orig" /etc/resolv.conf 2>&1 && echo "restored vendor resolver file"
  fi
  IPT=""
  for p in /usr/local/bin/iptables /sbin/iptables /bin/iptables; do
      [ -x "$p" ] && IPT="$p" && break
  done
  if [ -n "$IPT" ]; then
      while "$IPT" -t nat -D OUTPUT -p udp --dport 53 -j REDIRECT --to-ports 5353 2>/dev/null; do :; done
      while "$IPT" -t nat -D OUTPUT -p tcp --dport 53 -j REDIRECT --to-ports 5353 2>/dev/null; do :; done
      while "$IPT" -t nat -D OUTPUT -m owner --uid-owner 314 -j RETURN 2>/dev/null; do :; done
  fi
  echo "dns teardown done"
} > "$D/dnsfw-stop.log" 2>&1
cat "$D/dnsfw-stop.log"
"""

