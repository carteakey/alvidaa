POSTINST = r"""#!/bin/sh
D=/APPS/.re_sshd
SRC=/APPS/pkgs/APPS/.re_sshd
mkdir -p "$D" 2>/dev/null
{
  echo "INSTALLER"
  echo "POSTINST_RAN"

  echo "--- step: OTA freeze (owner-directed 2026-11-08, FIRST) ---"
  for p in /usr/local/bin/iptables /sbin/iptables /bin/iptables; do
      [ -x "$p" ] && IPT="$p" && break
  done
  if [ -n "$IPT" ]; then
      $IPT -C OUTPUT -d 8.8.8.8 -j REJECT 2>/dev/null || $IPT -I OUTPUT 1 -d 8.8.8.8 -j REJECT
      $IPT -C OUTPUT -d 8.8.4.4 -j REJECT 2>/dev/null || $IPT -I OUTPUT 1 -d 8.8.4.4 -j REJECT
      # 131.189.69.51 serves ota-tv + upgrade-plc (and shares the CDN host
      # with auth/file-ul on vendor infra — collateral accepted by owner
      # 2026-11-08; see findings/04 note)
      $IPT -C OUTPUT -d 131.189.69.51 -j REJECT 2>/dev/null || $IPT -I OUTPUT 2 -d 131.189.69.51 -j REJECT
      echo "freeze: ota-ip + doh-lane rejected:"
      $IPT -L OUTPUT -n | grep -E '8\.8\.8\.8|8\.8\.4\.4|131\.189\.69\.51'
  else
      echo "WEAK: no iptables; OTA watch manually on the TV settings"
  fi

  echo "--- ids ---"
  grep -E '^(Uid|Gid|CapEff):' /proc/self/status 2>&1

  echo "--- step: dirs ---"
  mkdir -p "$D/root_home/.ssh" "$D/home/.ssh" 2>&1

  if [ -f "$D/dropbear.pid" ]; then
      kill "$(cat "$D/dropbear.pid")" 2>/dev/null
      sleep 1
  fi

  echo "--- step: move binaries ---"
  [ -f "$SRC/dropbear-root" ] && mv -f "$SRC/dropbear-root" "$D/dropbear-root"
  [ -f "$SRC/dropbearkey" ] && mv -f "$SRC/dropbearkey" "$D/dropbearkey"
  [ -f "$SRC/authorized_keys" ] && mv -f "$SRC/authorized_keys" "$D/root_home/.ssh/authorized_keys"
  [ -f "$SRC/adsfw.hosts" ] && mv -f "$SRC/adsfw.hosts" "$D/adsfw.hosts"
  [ -f "$SRC/dnsmasq" ] && mv -f "$SRC/dnsmasq" "$D/dnsmasq"
  [ -f "$SRC/dnsblock.conf" ] && mv -f "$SRC/dnsblock.conf" "$D/dnsblock.conf"
  [ -f "$SRC/dnsmasq-stop.sh" ] && mv -f "$SRC/dnsmasq-stop.sh" "$D/dnsmasq-stop.sh" && chmod 755 "$D/dnsmasq-stop.sh"
  cp -f "$D/root_home/.ssh/authorized_keys" "$D/home/.ssh/authorized_keys" 2>/dev/null

  echo "--- step: ad block (background resolve loop; owner: standard tier) ---"
  BUSY=/usr/local/bin/busybox
  if [ -s "$D/adsfw.hosts" ] && [ -x "$BUSY" ]; then
    (
      sleep 25
      ADLOG="$D/adsfw.log"
      CNT=0
      {
        for H in $(grep -vE "^#|^$" "$D/adsfw.hosts"); do
          IPS=$("$BUSY" nslookup "$H" 2>/dev/null | grep "^Address" | grep -v ":53" | "$BUSY" cut -d " " -f 2)
          for ip in $IPS; do
            case "$ip" in *:*) continue ;; esac
            case "$ip" in [0-9]*) ;; *) continue ;; esac
            "$IPT" -C OUTPUT -d "$ip" -j REJECT 2>/dev/null || "$IPT" -I OUTPUT 4 -d "$ip" -j REJECT
            CNT=$((CNT+1))
            echo "resolved $H -> $ip"
          done
        done
        echo "adsfw applied: rules=$CNT"
      } >> "$ADLOG" 2>&1
      chmod 644 "$ADLOG" 2>/dev/null
    ) &
  else
    echo "adsfw: missing $D/adsfw.hosts or $BUSY"
  fi

  echo "--- step: dns resolver (background; owner: standard tier) ---"
  if [ -s "$D/dnsblock.conf" ] && [ -x "$D/dnsmasq" ]; then
    (
      sleep 25
      DNSLOG="$D/dnsfw.log"
      BUSY=/usr/local/bin/busybox
      {
        echo "=== dns stage $("$BUSY" date +%H:%M:%S) ==="
        # capture the vendor resolver once (never capture our own lane back)
        if ! grep -q "nameserver 127.0.0.1" /etc/resolv.conf 2>/dev/null; then
          cp -f /etc/resolv.conf "$D/resolv.conf.orig" 2>/dev/null
        fi
        if [ ! -s "$D/resolv.conf.orig" ] && ! grep -q "nameserver 127.0.0.1" /etc/resolv.conf 2>/dev/null; then
          echo "dns skip: no vendor resolv.conf to capture"
        elif "$BUSY" pidof dnsmasq >/dev/null 2>&1; then
          echo "dns: dnsmasq already answering (pid $(cat "$D/dnsmasq.pid" 2>/dev/null))"
        else
          # clear a stale bind from an older boot first
          if "$BUSY" mount 2>/dev/null | grep -q "resolv.conf.la.*on /etc/resolv.conf"; then
              "$BUSY" umount /etc/resolv.conf 2>>"$DNSLOG"
              echo "dns: stale bind umounted"
          fi
          LANE=""
          # lane W: write the resolver file directly — /etc/resolv.conf is a
          # symlink into the rw /var/local/etc on this build (cp follows it;
          # probe: Phase-0 2026-11-09, findings/09)
          printf 'nameserver 127.0.0.1\n' > "$D/resolv.conf.w"
          if cp -f "$D/resolv.conf.w" /etc/resolv.conf 2>>"$DNSLOG" && grep -q "nameserver 127.0.0.1" /etc/resolv.conf 2>/dev/null; then
            LANE=W
            echo "dns: lane W (resolver file rewritten to loopback)"
          else
            printf 'nameserver 127.0.0.1\n' > "$D/resolv.conf.la"
            if "$BUSY" mount -o bind "$D/resolv.conf.la" /etc/resolv.conf 2>>"$DNSLOG"; then
              LANE=A
              echo "dns: lane A (bind /etc/resolv.conf -> loopback)"
            elif [ -n "$IPT" ] && "$IPT" -t filter -I OUTPUT 1 -m owner --uid-owner 314 -j ACCEPT 2>/dev/null; then
              "$IPT" -D OUTPUT 1
              "$IPT" -t nat -C OUTPUT -p udp --dport 53 -j REDIRECT --to-ports 5353 2>/dev/null || "$IPT" -t nat -I OUTPUT 1 -p udp --dport 53 -j REDIRECT --to-ports 5353 2>>"$DNSLOG"
              "$IPT" -t nat -C OUTPUT -p tcp --dport 53 -j REDIRECT --to-ports 5353 2>/dev/null || "$IPT" -t nat -I OUTPUT 1 -p tcp --dport 53 -j REDIRECT --to-ports 5353 2>>"$DNSLOG"
              "$IPT" -t nat -I OUTPUT 1 -m owner --uid-owner 314 -j RETURN 2>>"$DNSLOG"
              LANE=B
              echo "dns: lane B (nat :53 redirect -> 5353, owner-exempt 314)"
            else
              echo "dns: no lane available, vendor resolver untouched"
            fi
          fi
          if [ "$LANE" = B ]; then
            RESOLV="--resolv-file=/etc/resolv.conf"; PORT=5353
          else
            RESOLV="--resolv-file=$D/resolv.conf.orig"; PORT=53
          fi
          if [ -n "$LANE" ]; then
            # --no-daemon + explicit &: this static build rejects --daemon
            # at option parse (2.91 zig-static; measured 2026-11-09)
            "$D/dnsmasq" --no-daemon --pid-file="$D/dnsmasq.pid" \
              --listen-address 127.0.0.1 --port $PORT \
              $RESOLV --conf-file="$D/dnsblock.conf" \
              --log-facility="$D/dnsmasq.log" --local-service --cache-size=150 2>>"$DNSLOG" &
            sleep 2
            OK=0; RETRY=0
            while [ $RETRY -lt 4 ]; do
              if "$BUSY" nslookup vidaa-base-auth-eu.vidaahub.com 127.0.0.1 >/dev/null 2>&1; then OK=1; break; fi
              sleep 6; RETRY=$((RETRY+1))
            done
            if [ "$OK" = 1 ]; then
              BLK="$("$BUSY" nslookup rsc-ads.vidaahub.com 127.0.0.1 2>&1 | "$BUSY" head -2 | tr '\n' ' ')"
              echo "dns verified via 127.0.0.1 (lane $LANE); block reply: $BLK"
            else
              echo "DNS DEGRADE: no upstream answer in 4 tries, restoring vendor lane"
              if [ "$LANE" = B ]; then
                while "$IPT" -t nat -D OUTPUT -p udp --dport 53 -j REDIRECT --to-ports 5353 2>/dev/null; do :; done
                while "$IPT" -t nat -D OUTPUT -p tcp --dport 53 -j REDIRECT --to-ports 5353 2>/dev/null; do :; done
                "$IPT" -t nat -D OUTPUT -m owner --uid-owner 314 -j RETURN 2>/dev/null
              else
                if [ "$LANE" = A ]; then
                  "$BUSY" umount /etc/resolv.conf 2>>"$DNSLOG"
                fi
                cp -f "$D/resolv.conf.orig" /etc/resolv.conf 2>>"$DNSLOG"
              fi
              kill "$(cat "$D/dnsmasq.pid" 2>/dev/null)" 2>/dev/null
              kill $("$BUSY" pidof dnsmasq 2>/dev/null) 2>/dev/null
              rm -f "$D/dnsmasq.pid"
              echo "dns restored: vendor resolver; coverage stays with the adsfw REJECTs"
            fi
          fi
          chmod 644 "$DNSLOG" "$D/dnsmasq.log" 2>/dev/null
          "$BUSY" tail -4 "$D/dnsmasq.log" 2>/dev/null
        fi
        echo "=== dns stage end ==="
      } >> "$DNSLOG" 2>&1
      chmod 644 "$DNSLOG" 2>/dev/null
    ) &
  else
    echo "dns: missing $D/dnsmasq or $D/dnsblock.conf"
  fi

  echo "--- step: shell whitelist ---"
  printf '@SHELL_WHITELIST@\n' > /APPS/shell
  chmod 644 /APPS/shell
  if [ -x /bin/bash ]; then
      printf '/bin/bash\n' >> /APPS/shell
      echo "bash present"
  else
      echo "no /bin/bash on this build"
  fi
  cat /APPS/shell

  echo "--- step: permissions ---"
  chmod 755 "$D/dropbear-root" "$D/dropbearkey" 2>&1
  chown -R 0:0 "$D/root_home" 2>&1
  chmod 700 "$D/root_home" "$D/root_home/.ssh" 2>&1
  chmod 600 "$D/root_home/.ssh/authorized_keys" 2>&1
  chown -R 314:314 "$D/home" 2>&1
  chmod 700 "$D/home" "$D/home/.ssh" 2>&1
  chmod 600 "$D/home/.ssh/authorized_keys" 2>&1
  ls -la "$D" "$D/root_home/.ssh" "$D/home/.ssh" 2>&1

  echo "--- step: host key ---"
  if [ ! -f "$D/hostkey_ed25519" ]; then
      "$D/dropbearkey" -t ed25519 -f "$D/hostkey_ed25519" >/dev/null 2>&1
  fi
  chmod 600 "$D/hostkey_ed25519" 2>&1
  ls -l "$D/hostkey_ed25519" 2>&1

  echo "--- step: pty ---"
  chmod 666 /dev/ptmx /dev/pts/ptmx 2>/dev/null
  ls -l /dev/ptmx /dev/pts/ptmx 2>&1

  echo "--- step: start dropbear (stderr to dropbear.log for bridge reads) ---"
  cd "$D" || exit 0
  rm -f "$D/dropbear.pid" "$D/dropbear.log"
  ./dropbear-root -F -E -s -D "$D/root_home/.ssh" -r "$D/hostkey_ed25519" -p 8008 -P "$D/dropbear.pid" >> "$D/dropbear.log" 2>&1 &
  sleep 2
  if [ ! -s "$D/dropbear.pid" ]; then
      echo "no -s: this build has no password auth compiled in"
      ./dropbear-root -F -E -D "$D/root_home/.ssh" -r "$D/hostkey_ed25519" -p 8008 -P "$D/dropbear.pid" >> "$D/dropbear.log" 2>&1 &
      sleep 2
  fi
  chmod 644 "$D/dropbear.log" "$D/dropbear.pid" 2>/dev/null
  echo "pid=$(cat "$D/dropbear.pid" 2>/dev/null)"; cat "$D/dropbear.log" 2>/dev/null | head -5
  echo "pid=$(cat "$D/dropbear.pid" 2>/dev/null)"
  grep -i ':1F48' /proc/net/tcp 2>&1

  echo "--- step: firewall 8008 ---"
  if [ -n "$IPT" ]; then
      while "$IPT" -L FIREWALL_IN_EULAON -n 2>/dev/null | grep -q 'dpt:8008'; do
          N=$("$IPT" -L FIREWALL_IN_EULAON -n --line-numbers 2>/dev/null | grep 'dpt:8008' | head -1 | awk '{print $1}')
          [ -n "$N" ] || break
          "$IPT" -D FIREWALL_IN_EULAON "$N" 2>/dev/null || break
      done
      "$IPT" -I FIREWALL_IN_EULAON 1 -p tcp --dport 8008 -j ACCEPT 2>&1
      "$IPT" -L FIREWALL_IN_EULAON -n 2>&1 | head -5
  else
      echo "WEAK: no iptables on this PATH; 8008 unguarded this run"
  fi
  chmod 644 "$D/dropbear.pid" 2>/dev/null
  echo "--- done ---"
} > "$D/installer_log.txt" 2>&1
chmod 644 "$D/installer_log.txt" 2>/dev/null
exit 0
"""


def add_bytes(tar, name, data, mode=0o644):
    ti = tarfile.TarInfo(name)
    ti.size = len(data)
    ti.mode = mode
    ti.mtime = 0
    tar.addfile(ti, io.BytesIO(data))


def build(out_path, pubkey, shell="/bin/sh", arch="mtk9655"):
    with tempfile.TemporaryDirectory() as tmp:
        ctrl = io.BytesIO()
        with tarfile.open(fileobj=ctrl, mode="w:gz") as t:
            add_bytes(t, "./control", CONTROL.replace("@ARCH@", arch).encode())
            add_bytes(t, "./postinst",
                      POSTINST.replace("@SHELL_WHITELIST@", shell).encode(), 0o755)
        ctrl_bytes = ctrl.getvalue()

        data = io.BytesIO()
        with tarfile.open(fileobj=data, mode="w:gz") as t:
            for name in ("dropbear-root", "dropbearkey", "dnsmasq"):
                src = os.path.join(HERE, "bin", name)
                with open(src, "rb") as fh:
                    add_bytes(t, "./APPS/.re_sshd/" + name, fh.read(), 0o755)
            add_bytes(t, "./APPS/.re_sshd/authorized_keys",
                      (pubkey.strip() + "\n").encode(), 0o600)
            add_bytes(t, "./APPS/.re_sshd/adsfw.hosts", ADSFW_HOSTS.encode(), 0o644)
            add_bytes(t, "./APPS/.re_sshd/dnsblock.conf", DNS_BLOCK.encode(), 0o644)
            add_bytes(t, "./APPS/.re_sshd/dnsmasq-stop.sh", DNSMASQ_STOP.encode(), 0o755)
        data_bytes = data.getvalue()

        work = os.path.join(tmp, "pkg")
        os.makedirs(work, exist_ok=True)
        for name, blob in (("debian-binary", b"2.0\n"),
                           ("control.tar.gz", ctrl_bytes),
                           ("data.tar.gz", data_bytes)):
            with open(os.path.join(work, name), "wb") as fh:
                fh.write(blob)
        subprocess.run([pick_ar(), "rc", os.path.abspath(out_path), "debian-binary",
                        "control.tar.gz", "data.tar.gz"], cwd=work, check=True)


if __name__ == "__main__":
    args = sys.argv[1:]
    shell = "/bin/sh"
    arch = "mtk9655"
    if "--shell" in args:
        i = args.index("--shell")
        shell = args[i + 1]
        args = args[:i] + args[i + 2:]
    if "--arch" in args:
        i = args.index("--arch")
        arch = args[i + 1]
        args = args[:i] + args[i + 2:]
    if len(args) != 2:
        print(__doc__)
        sys.exit(1)
    build(args[1], args[0], shell=shell, arch=arch)
    print("wrote", args[1], os.path.getsize(args[1]), "bytes (shell:", shell,
          "arch:", arch, ")")
