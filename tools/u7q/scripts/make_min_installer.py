#!/usr/bin/env python3
"""Build a minimal VIDAA U09.60 root-dropbear IPK (75U8QTUK / 100U7Q chain).

Usage:  python3 make_min_installer.py "<ssh-ed25519 AAAA... comment>" out.ipk

Unlike scripts/make_installer.py, this postinst does only what the 100U7Q
root recipe needs:

  - move the bundled dropbear binaries out of /APPS/pkgs/APPS/.re_sshd
  - install the public key for root (and the uid-314 "re" account)
  - write /APPS/shell (the patched getusershell() path)
  - generate the ed25519 host key if absent
  - open /dev/ptmx + /dev/pts/ptmx for PTY
  - start dropbear key-only on 0.0.0.0:8008
  - accept inbound 8008 in the vendor firewall chain (deduped)
  - write /APPS/.re_sshd/installer_log.txt (POSTINST_RAN, Uid, CapEff, pid)

Two owner-scoped background stages are included (both 55E7QTUK lanes, both
idempotent on the every-boot re-fire — see findings/08 and findings/09):

  - adsfw: per-IP OUTPUT REJECTs for the ad/telemetry host families
  - dns resolver: static dnsmasq on loopback, domain-level block of the
    same families; lane A = bind-mount over /etc/resolv.conf (ro-safe),
    lane B = nat REDIRECT + owner-exempt upstream (if lane A unavailable);
    safe-degrade restores the vendor resolver if verification fails.

Nothing is device-specific except the public key passed on the command line.
"""
import io
import os
import platform
import subprocess
import sys
import tarfile


def pick_ar():
    """macOS LLVM ar silently drops non-mach-o members from `ar rc` archives,
    yielding 96-byte ipk shells — use GNU binutils' gar when present."""
    if platform.system() != "Darwin":
        return "ar"
    try:
        prefix = subprocess.check_output(["brew", "--prefix", "binutils"],
                                         text=True).strip()
        gar = os.path.join(prefix, "bin", "gar")
        if os.path.exists(gar):
            return gar
    except Exception:
        pass
    return "ar"
import tempfile

